import { ACTIONS, ROLES, type PermissionTable } from '@sodiq/shared';
import type { ExpectedAccess } from './route-harness.js';
import type { IdKind, RouteIds } from './route-id-check.js';
import type { RouteScopes } from './route-scope-check.js';

/** The markers between which `docs/security/permission-checklist.md` is written from the code. */
export const GENERATED_START = '<!-- generated by pnpm security:checklist: start -->';
export const GENERATED_END = '<!-- generated by pnpm security:checklist: end -->';

export interface ChecklistSources {
  table: PermissionTable;
  publicRoutes: Readonly<Record<string, string>>;
  stepRoutes: Readonly<Record<string, readonly string[]>>;
  access: Readonly<Record<string, ExpectedAccess>>;
  scopes: RouteScopes;
  ids: RouteIds;
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function tableOf(table: PermissionTable): string[] {
  const lines = ['## The permission table', ''];
  lines.push(
    'Every area of `PERMISSIONS` (`packages/shared/src/permissions.ts`), the table the server guard reads on every request. A role not named in an area may do nothing there.',
    '',
  );
  for (const area of Object.keys(table).sort()) {
    const rows = table[area];
    if (rows === undefined) {
      continue;
    }
    lines.push(`### \`${area}\``, '');
    lines.push(
      `| Role | ${ACTIONS.join(' | ')} |`,
      `| --- |${ACTIONS.map(() => ' :-: |').join('')}`,
    );
    let named = 0;
    for (const role of ROLES) {
      const actions = rows[role];
      if (actions.length === 0) {
        continue;
      }
      named += 1;
      lines.push(
        `| ${role} | ${ACTIONS.map((action) => (actions.includes(action) ? 'yes' : '')).join(' | ')} |`,
      );
    }
    if (named === 0) {
      lines.push(`| (nobody) |${ACTIONS.map(() => ' |').join('')}`);
    }
    lines.push('');
  }
  return lines;
}

function routesWithoutRole(sources: ChecklistSources): string[] {
  const lines = ['## Routes without a role', ''];
  lines.push(
    'Without sign-in (`PUBLIC_ROUTES`, `apps/api/src/testing/route-access-list.ts`; held exact by `public-routes.test.ts`):',
    '',
    '| Route | Why it needs no sign-in |',
    '| --- | --- |',
  );
  for (const [route, reason] of Object.entries(sources.publicRoutes).sort()) {
    lines.push(`| \`${route}\` | ${cell(reason)} |`);
  }
  lines.push('', 'Every signed-in account, for its own account only (`@AnySignedIn`):', '');
  for (const [route, listed] of Object.entries(sources.access).sort()) {
    if (listed === 'any_signed_in') {
      lines.push(`- \`${route}\``);
    }
  }
  lines.push(
    '',
    'Reachable while a step of sign-in is still owed (`STEP_ROUTES`; held exact by `route-permissions.test.ts`):',
    '',
    '| Route | Owed steps |',
    '| --- | --- |',
  );
  for (const [route, steps] of Object.entries(sources.stepRoutes).sort()) {
    lines.push(`| \`${route}\` | ${steps.join(', ')} |`);
  }
  lines.push('');
  return lines;
}

function limitsOf(sources: ChecklistSources): string[] {
  const lines = ['## Limits inside the routes', ''];
  lines.push(
    'For every route that lets in a role for less than its whole branch, the limit of each role and the tests that prove the refusal (`ROUTE_SCOPE`, `apps/api/src/testing/route-scope-list.ts`; held complete by `route-scopes.test.ts`). `branch` means the spec gives that role the whole branch on this route.',
    '',
    '| Route | Roles | Limit | Rule | Proved by |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const [route, scopeLines] of Object.entries(sources.scopes).sort()) {
    for (const line of scopeLines) {
      const tests = line.refusedIn.map((test) => `\`${cell(test)}\``).join('<br>');
      lines.push(
        `| \`${route}\` | ${line.roles.join(', ')} | ${line.scope} | ${cell(line.rule)} | ${tests === '' ? '—' : tests} |`,
      );
    }
  }
  lines.push('');
  return lines;
}

function idsOf(sources: ChecklistSources): string[] {
  const lines = ['## Records of another branch by id', ''];
  lines.push(
    "For every id a route takes, in its path, its query or its body, the record it names and the tests that send another branch's id and an unknown one and see 404, with the rows of both branches and the audit log unchanged, or for a query filter none of the other branch's matching rows answered (`ROUTE_IDS`, `apps/api/src/testing/route-id-list.ts`; held complete by `route-ids.test.ts`, which reads the ids from the OpenAPI document). `school`: a record of the whole school; `own`: a record of the signed-in account, refused for another account; `none`: no record. A route with a request key also names the tests that repeat a used key with another branch's id.",
    '',
    '| Route | Id | Record | Kind | Proved by |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const [route, idLines] of Object.entries(sources.ids).sort()) {
    for (const line of idLines) {
      const tests = [...line.refusedIn, ...(line.repeatIn ?? []).map((test) => `repeat: ${test}`)]
        .map((test) => `\`${cell(test)}\``)
        .join('<br>');
      lines.push(
        `| \`${route}\` | \`${cell(line.id)}\` | ${cell(line.record)} | ${line.kind} | ${tests === '' ? cell(line.rule) : tests} |`,
      );
    }
  }
  lines.push('');
  return lines;
}

function countsOf(sources: ChecklistSources): string[] {
  const routes = Object.values(sources.access);
  const withRole = routes.filter((listed) => typeof listed !== 'string').length;
  return [
    '## The routes in numbers',
    '',
    `- Routes of the application: ${String(routes.length)}, each called by the role harness as the 15 roles, an account without a role and nobody, in the own and in another branch.`,
    `- Without sign-in: ${String(Object.keys(sources.publicRoutes).length)}. For the own account: ${String(routes.filter((listed) => listed === 'any_signed_in').length)}. With a permission of the table: ${String(withRole)}.`,
    `- Routes with a limit inside the route: ${String(Object.keys(sources.scopes).length)}.`,
    `- Routes that take an id: ${String(Object.keys(sources.ids).length)}, with ${String(idCount(sources.ids))} ids (${(['branch', 'school', 'own', 'none'] as const).map((kind) => `${kind} ${String(idCount(sources.ids, kind))}`).join(', ')}).`,
    `- Areas of the permission table: ${String(Object.keys(sources.table).length)}.`,
    '',
  ];
}

function idCount(ids: RouteIds, kind?: IdKind): number {
  return Object.values(ids)
    .flat()
    .filter((line) => kind === undefined || line.kind === kind).length;
}

/** The part of the checklist that is read from the code, between the two markers. */
export function renderGenerated(sources: ChecklistSources): string {
  return [
    GENERATED_START,
    '',
    ...countsOf(sources),
    ...routesWithoutRole(sources),
    ...limitsOf(sources),
    ...idsOf(sources),
    ...tableOf(sources.table),
    GENERATED_END,
  ].join('\n');
}

/** The checklist with its generated part written again; the hand-written text around it is kept. */
export function withGenerated(document: string, generated: string): string {
  const start = document.indexOf(GENERATED_START);
  const end = document.indexOf(GENERATED_END);
  if (start < 0 || end < start) {
    throw new Error('The checklist has lost its generated markers.');
  }
  return document.slice(0, start) + generated + document.slice(end + GENERATED_END.length);
}
