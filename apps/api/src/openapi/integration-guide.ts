const METHODS = ['get', 'put', 'post', 'delete', 'patch'] as const;

/** The start of the pattern Zod writes for a UUID. */
const UUID_PATTERN_START = '^([0-9a-fA-F]{8}';

/** A shared answer shape longer than this is shown once and referred to after. */
const REFER_AFTER_LINES = 12;

interface KeyOperation {
  path: string;
  method: string;
  operation: GuideOperation;
}

/** The operations of the document open to keys, in the order of its paths. */
export function keyOperations(document: GuideDocument): KeyOperation[] {
  const found: KeyOperation[] = [];
  for (const [path, item] of Object.entries(document.paths)) {
    for (const method of METHODS) {
      const operation = item[method];
      if (operation?.[OPEN_TO_KEYS] === true) {
        found.push({ path, method: method.toUpperCase(), operation });
      }
    }
  }
  return found;
}

function resolve(document: GuideDocument, schema: GuideSchema): GuideSchema {
  if (schema.$ref === undefined) {
    return schema;
  }
  const name = schema.$ref.split('/').pop() ?? '';
  const target = document.components?.schemas?.[name];
  if (target === undefined) {
    throw new Error(`The schema ${schema.$ref} is not in the document.`);
  }
  return target;
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** A bound worth showing: the largest safe integer is Zod's default for `.int()`. */
function shown(bound: number | undefined): bound is number {
  return bound !== undefined && Math.abs(bound) !== Number.MAX_SAFE_INTEGER;
}

function limits(schema: GuideSchema): string[] {
  const parts: string[] = [];
  if (shown(schema.minimum)) parts.push(`min ${String(schema.minimum)}`);
  if (shown(schema.exclusiveMinimum)) parts.push(`> ${String(schema.exclusiveMinimum)}`);
  if (shown(schema.maximum)) parts.push(`max ${String(schema.maximum)}`);
  if (shown(schema.exclusiveMaximum)) parts.push(`< ${String(schema.exclusiveMaximum)}`);
  if (schema.minLength !== undefined) parts.push(`length ≥ ${String(schema.minLength)}`);
  if (schema.maxLength !== undefined) parts.push(`length ≤ ${String(schema.maxLength)}`);
  if (schema.minItems !== undefined) parts.push(`items ≥ ${String(schema.minItems)}`);
  if (schema.maxItems !== undefined) parts.push(`items ≤ ${String(schema.maxItems)}`);
  return parts;
}

function literal(value: unknown): string {
  return JSON.stringify(value) ?? 'unknown';
}

/** A schema as a compact TypeScript-like type, indented by `depth` steps. */
function typeOf(document: GuideDocument, schemaIn: GuideSchema | undefined, depth: number): string {
  if (schemaIn === undefined) {
    return 'unknown';
  }
  const schema = resolve(document, schemaIn);
  if (Object.keys(schema).length === 0) {
    return 'unknown';
  }
  const pad = '  '.repeat(depth);
  if (schema.const !== undefined) {
    return literal(schema.const);
  }
  if (schema.enum !== undefined) {
    return schema.enum.map(literal).join(' | ');
  }
  const union = schema.anyOf ?? schema.oneOf;
  if (union !== undefined) {
    return [...new Set(union.map((part) => typeOf(document, part, depth)))].join(' | ');
  }
  if (schema.allOf !== undefined) {
    return schema.allOf.map((part) => typeOf(document, part, depth)).join(' & ');
  }
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const nullable = types.includes('null') || schema.nullable === true;
  let out: string;
  if (types.includes('object') || schema.properties !== undefined) {
    const properties = schema.properties ?? {};
    const required = new Set(schema.required ?? []);
    const names = Object.keys(properties);
    if (names.length === 0) {
      const values = schema.additionalProperties;
      out =
        values !== undefined && typeof values !== 'boolean'
          ? `Record<string, ${typeOf(document, values, depth)}>`
          : '{}';
    } else {
      const lines = names.map((name) => {
        const property = properties[name];
        const note = property === undefined ? [] : limits(resolve(document, property));
        const comment = note.length > 0 ? `  // ${note.join(', ')}` : '';
        const optional = required.has(name) ? '' : '?';
        return `${pad}  ${propertyKey(name)}${optional}: ${typeOf(document, property, depth + 1)};${comment}`;
      });
      out = `{\n${lines.join('\n')}\n${pad}}`;
    }
  } else if (types.includes('array')) {
    const item = typeOf(document, schema.items, depth);
    out = /[|&]/.test(item) && !item.startsWith('{') ? `(${item})[]` : `${item}[]`;
  } else if (types.includes('string')) {
    if (schema.format === 'uuid' || schema.pattern?.startsWith(UUID_PATTERN_START) === true) {
      out = 'uuid';
    } else if (
      schema.format === 'date' ||
      schema.format === 'date-time' ||
      schema.format === 'binary'
    ) {
      out = schema.format;
    } else if (schema.pattern !== undefined) {
      out = `string /* ${schema.pattern} */`;
    } else {
      out = 'string';
    }
  } else if (types.includes('integer')) {
    out = 'integer';
  } else if (types.includes('number')) {
    out = 'number';
  } else if (types.includes('boolean')) {
    out = 'boolean';
  } else {
    out = 'unknown';
  }
  return nullable ? `${out} | null` : out;
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replace(/\n\s*/g, ' ');
}

/**
 * The operations open to keys as Markdown, between the markers: one section per
 * group, each operation with its text, parameters, request body and answer.
 */
export function renderKeyOperations(document: GuideDocument): string {
  const operations = keyOperations(document);
  const missing = operations
    .map(({ operation }) => operation.operationId ?? '')
    .filter((id) => KEY_OPERATION_TEXTS[id] === undefined);
  if (missing.length > 0) {
    throw new Error(
      `Operations open to keys without a text in KEY_OPERATION_TEXTS: ${missing.join(', ')}`,
    );
  }
  const used = new Set<KeyOperation>();
  const firstAnswer = new Map<string, number>();
  const out: string[] = [OPERATIONS_START, ''];
  let index = 0;
  for (const [title, takes] of GROUPS) {
    const mine = operations.filter((one) => !used.has(one) && takes(one.path));
    if (mine.length === 0) {
      continue;
    }
    out.push(`### ${title}`, '');
    for (const one of mine) {
      used.add(one);
      index += 1;
      const { operation } = one;
      out.push(`#### ${String(index)}. \`${one.method} ${one.path}\``, '');
      out.push(KEY_OPERATION_TEXTS[operation.operationId ?? ''] ?? '', '');
      const parameters = operation.parameters ?? [];
      const notes = [
        parameters.some((p) => p.name === 'X-Branch-Id')
          ? 'Needs `X-Branch-Id`.'
          : 'No `X-Branch-Id`.',
      ];
      if (parameters.some((p) => p.name === 'Idempotency-Key')) {
        notes.push('Takes `Idempotency-Key`.');
      }
      out.push(notes.join(' '), '');
      const listed = parameters.filter(
        (p) => p.name !== 'X-Branch-Id' && p.name !== 'Idempotency-Key',
      );
      if (listed.length > 0) {
        out.push('| Parameter | In | Required | Type |', '| --- | --- | --- | --- |');
        for (const p of listed) {
          out.push(
            `| \`${p.name}\` | ${p.in} | ${p.required === true ? 'yes' : 'no'} | \`${cell(typeOf(document, p.schema, 0))}\` |`,
          );
        }
        out.push('');
      }
      const body = operation.requestBody?.content;
      if (body !== undefined) {
        const kinds = Object.keys(body);
        const json = body['application/json'];
        if (kinds.length === 1 && json !== undefined) {
          out.push(
            'Request body (`application/json`):',
            '',
            '```ts',
            typeOf(document, json.schema, 0),
            '```',
            '',
          );
        } else {
          out.push(
            `Request body: the file itself, as raw bytes, with \`Content-Type\` one of: ${kinds.map((kind) => `\`${kind}\``).join(', ')}.`,
            '',
          );
        }
      } else if (one.method !== 'GET' && one.method !== 'DELETE') {
        out.push('No request body.', '');
      }
      const code = Object.keys(operation.responses)
        .filter((status) => /^2\d\d$/.test(status))
        .sort()[0];
      const content = code === undefined ? undefined : operation.responses[code]?.content;
      const json = content?.['application/json'];
      if (code === undefined) {
        out.push('No answer body.', '');
      } else if (json?.schema !== undefined) {
        const shape = typeOf(document, json.schema, 0);
        const first = firstAnswer.get(shape);
        if (first !== undefined && shape.split('\n').length > REFER_AFTER_LINES) {
          out.push(`Answer \`${code}\`: the same shape as the answer of #${String(first)}.`, '');
        } else {
          if (first === undefined) {
            firstAnswer.set(shape, index);
          }
          out.push(`Answer \`${code}\`:`, '', '```ts', shape, '```', '');
        }
      } else if (content !== undefined && Object.keys(content).length > 0) {
        out.push(`Answer \`${code}\`: the file, with its own \`Content-Type\`.`, '');
      } else {
        out.push(`Answer \`${code}\`, no body.`, '');
      }
    }
  }
  const left = operations.filter((one) => !used.has(one));
  if (left.length > 0) {
    throw new Error(
      `Operations open to keys in no section of the guide: ${left.map((one) => `${one.method} ${one.path}`).join(', ')}`,
    );
  }
  out.push(OPERATIONS_END);
  return out.join('\n');
}

/** The guide with its generated part replaced; the hand-written text around it is kept. */
export function withKeyOperations(guide: string, generated: string): string {
  const start = guide.indexOf(OPERATIONS_START);
  const end = guide.indexOf(OPERATIONS_END);
  if (start < 0 || end < start) {
    throw new Error('The integration guide has lost its generated markers.');
  }
  return guide.slice(0, start) + generated + guide.slice(end + OPERATIONS_END.length);
}
