/**
 * The operations open to integration keys, written into `docs/integration-guide.md`
 * from the OpenAPI document (the owner, 21 November 2026: the guide for the
 * department platforms stays up to date with the code). `pnpm api:client` writes
 * the part between the markers; `integration-guide.test.ts` fails when it is out of
 * date, or when an operation open to keys has no text below.
 */

/** The guide, from the repository root. */
export const INTEGRATION_GUIDE = 'docs/integration-guide.md';

/** The markers between which the operations are written from the code. */
export const OPERATIONS_START = '<!-- generated by pnpm api:client: start -->';
export const OPERATIONS_END = '<!-- generated by pnpm api:client: end -->';

/** The mark of an operation open to keys (`OPEN_TO_KEYS_EXTENSION` of `key-routes.ts`). */
const OPEN_TO_KEYS = 'x-open-to-integration-keys';

/** The parts of a schema the guide shows, as `openapi.generated.json` writes them. */
export interface GuideSchema {
  $ref?: string;
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  anyOf?: GuideSchema[];
  oneOf?: GuideSchema[];
  allOf?: GuideSchema[];
  properties?: Record<string, GuideSchema>;
  required?: string[];
  additionalProperties?: GuideSchema | boolean;
  items?: GuideSchema;
  format?: string;
  pattern?: string;
  nullable?: boolean;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
  exclusiveMaximum?: number;
  minLength?: number;
  maxLength?: number;
  minItems?: number;
  maxItems?: number;
}

interface GuideMedia {
  schema?: GuideSchema;
}

interface GuideParameter {
  name: string;
  in: string;
  required?: boolean;
  schema?: GuideSchema;
}

export interface GuideOperation {
  operationId?: string;
  parameters?: GuideParameter[];
  requestBody?: { content: Record<string, GuideMedia> };
  responses: Record<string, { content?: Record<string, GuideMedia> } | undefined>;
  [OPEN_TO_KEYS]?: boolean;
}

/** The parts of `openapi.generated.json` the guide reads. */
export interface GuideDocument {
  paths: Record<string, Record<string, GuideOperation | undefined>>;
  components?: { schemas?: Record<string, GuideSchema> };
}

